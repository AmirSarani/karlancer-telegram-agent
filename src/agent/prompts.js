/**
 * Build system prompt for a stage.
 * @param {'analyze'|'write'|'reply'} stage
 * @param {string} [extraTone]
 */
export function buildSystemPrompt(stage, extraTone = '') {
  const map = {
    analyze: ANALYZE_SYSTEM,
    write: WRITE_PROPOSAL_SYSTEM,
    reply: REPLY_SYSTEM,
  };
  let out = map[stage] || ANALYZE_SYSTEM;
  const tone = (extraTone || '').trim();
  if (tone) {
    out += `\n\n--- لحن اضافی (فقط سبک؛ قوانین صداقت و نگارش فارسی را نقض نکن) ---\n${tone}`;
  }
  return out;
}

